/**
 * LLM Wiki Architecture & Two-Pass Retrieval Engine (Andrej Karpathy Model)
 * Week 03 Day 06 - JavaScript / Node.js Implementation
 * 
 * Key Features:
 * 1. Categorized Markdown / Obsidian Wiki Vault metadata storage.
 * 2. Two-Pass Retrieval Workflow:
 *    - Pass 1: Scan titles, metadata tags, and summaries across vault (0% raw text loaded).
 *    - Pass 2: Selective full-content lazy loading for ONLY candidate files chosen in Pass 1.
 */

export class WikiFileEntry {
  /**
   * @param {string} filePath - Path relative to vault (e.g. 'infrastructure/alb-config.md')
   * @param {string} title - Human readable title
   * @param {string} category - Vault category / directory name
   * @param {string[]} tags - Metadata keywords
   * @param {string} summary - High-level semantic abstract generated by LLM Librarian
   * @param {string} rawContent - Full Markdown raw content
   */
  constructor(filePath, title, category, tags, summary, rawContent) {
    this.filePath = filePath;
    this.title = title;
    this.category = category;
    this.tags = tags;
    this.summary = summary;
    this.rawContent = rawContent;
  }

  /**
   * Returns lightweight metadata for Pass 1 scan.
   */
  getMetadata() {
    return {
      filePath: this.filePath,
      title: this.title,
      category: this.category,
      tags: this.tags,
      summary: this.summary
    };
  }
}

export class LLMWikiVault {
  constructor() {
    /** @type {Map<string, WikiFileEntry>} */
    this.files = new Map();
  }

  /**
   * Add a file to the Wiki vault catalog.
   * @param {WikiFileEntry} entry 
   */
  addFile(entry) {
    this.files.set(entry.filePath, entry);
  }

  /**
   * Returns metadata array for ALL wiki files in vault.
   */
  listCatalogMetadata() {
    return Array.from(this.files.values()).map(entry => entry.getMetadata());
  }

  /**
   * Pass 2: Lazy-loads full raw text of targeted file.
   * @param {string} filePath 
   */
  readFileContent(filePath) {
    if (this.files.has(filePath)) {
      return this.files.get(filePath).rawContent;
    }
    throw new Error(`File '${filePath}' not found in Wiki Vault catalog.`);
  }
}

export class TwoPassWikiRetriever {
  /**
   * @param {LLMWikiVault} vault 
   */
  constructor(vault) {
    this.vault = vault;
  }

  /**
   * Executes the two-pass scan retrieval algorithm.
   * @param {string} query 
   */
  searchAndRetrieve(query) {
    console.log(`\n🔍 [User Query Prompt]: "${query}"`);

    // -----------------------------------------------------------------
    // PASS 1: Lightweight Metadata & Summary Scan across catalog
    // -----------------------------------------------------------------
    console.log(`\n⚡ [PASS 1]: Scanning File Titles, Metadata Tags & Summaries (0% Raw Content Loaded)...`);
    const catalog = this.vault.listCatalogMetadata();
    const queryTerms = query.toLowerCase().split(/\s+/);

    const candidates = [];

    for (const meta of catalog) {
      const metaText = `${meta.title} ${meta.summary} ${meta.tags.join(' ')}`.toLowerCase();
      let score = 0;

      for (const term of queryTerms) {
        if (term.length > 2 && metaText.includes(term)) {
          score += 2;
        }
      }

      console.log(`   • Inspected Metadata for '${meta.filePath}' -> Match Score: ${score}`);
      if (score > 0) {
        candidates.push({ filePath: meta.filePath, score });
      }
    }

    candidates.sort((a, b) => b.score - a.score);

    if (candidates.length === 0) {
      console.log(`❌ No matching wiki files found during Pass 1 scan.`);
      return null;
    }

    const selectedFilePath = candidates[0].filePath;
    console.log(`🎯 [PASS 1 RESULT]: LLM Librarian Selected Candidate File -> '${selectedFilePath}'`);

    // -----------------------------------------------------------------
    // PASS 2: Selective Full Content Loading
    // -----------------------------------------------------------------
    console.log(`\n📖 [PASS 2]: Lazy-loading full text ONLY for '${selectedFilePath}'...`);
    const rawText = this.vault.readFileContent(selectedFilePath);

    return {
      selectedFile: selectedFilePath,
      candidatesList: candidates.map(c => c.filePath),
      retrievedFullContent: rawText
    };
  }
}


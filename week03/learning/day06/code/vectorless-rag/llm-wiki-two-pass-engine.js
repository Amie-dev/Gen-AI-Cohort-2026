export function buildSampleWikiVault() {
  const vault = new LLMWikiVault();

  vault.addFile(new WikiFileEntry(
    "vault/infrastructure/cdn-setup.md",
    "CDN Edge Caching Configuration Guide",
    "infrastructure",
    ["cdn", "cache", "edge", "cloudflare"],
    "Configuring Cloudflare CDN edge rules, TTL headers, and static asset distribution.",
    "CDN Full Text: Edge caching rules configured for static assets with 24h TTL..."
  ));

  vault.addFile(new WikiFileEntry(
    "vault/infrastructure/alb-sticky-sessions.md",
    "Application Load Balancer (ALB) Sticky Sessions & Cookies",
    "infrastructure",
    ["alb", "load-balancer", "sticky-sessions", "cookies", "aws"],
    "Explains AWS ALB sticky sessions, cookie expiration, encrypted session cookies, and sticky routing behavior.",
    `# ALB Sticky Sessions Guide
When sticky sessions are enabled on the AWS Application Load Balancer (ALB), 
the load balancer binds a user's session to a specific backend instance.

Key Cookie: AWSALB (Encrypted, 7-day default lifespan)
Failover Behavior: If sticky target instance drops out of target group, ALB assigns new sticky node.`
  ));

  vault.addFile(new WikiFileEntry(
    "vault/databases/postgres-replication.md",
    "PostgreSQL Primary-Replica Failover Mechanics",
    "databases",
    ["postgres", "database", "replication", "failover"],
    "Primary-replica streaming replication, WAL logs, and automatic Patroni failover.",
    "Postgres Full Text: WAL logs are streamed to standby replicas..."
  ));

  return vault;
}

